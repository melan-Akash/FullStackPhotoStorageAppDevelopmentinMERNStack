import cloudinary from '../config/cloudinary.js';
import { Media } from '../models/media.js';
import { Album } from '../models/album.js';

// Helper function to stream buffer directly to Cloudinary
const uploadToCloudinary = (fileBuffer, options) => {
  return new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(options, (error, result) => {
      if (result) resolve(result);
      else reject(error);
    });
    stream.end(fileBuffer);
  });
};

// Upload media files to Cloudinary and persist metadata
export const uploadMedia = async (req, res) => {
  try {
    if (!req.files || req.files.length === 0) {
      return res.status(400).json({ message: 'No files uploaded' });
    }

    const uploadedMedia = [];

    for (const file of req.files) {
      const isVideo = file.mimetype.startsWith('video/');
      const folderName = isVideo ? 'my_videos' : 'my_photos';

      // Cloudinary upload stream execution
      const cloudinaryResult = await uploadToCloudinary(file.buffer, {
        folder: folderName,
        resource_type: 'auto',
        categorization: 'google_tagging', // Auto-generate AI tags
        auto_tagging: 0.6,
      });

      // Extract autogenerated tags/objects for search filtering
      const detectedObjects = cloudinaryResult.tags || [];

      // Create video thumbnail URL if media is video
      let thumbnailUrl = cloudinaryResult.secure_url;
      if (isVideo) {
        thumbnailUrl = cloudinaryResult.secure_url.replace(/\.[^/.]+$/, '.jpg');
      }

      const item = await Media.create({
        title: file.originalname || (isVideo ? 'Untitled Video' : 'Untitled Photo'),
        url: cloudinaryResult.secure_url,
        thumbnailUrl: thumbnailUrl,
        publicId: cloudinaryResult.public_id,
        size: cloudinaryResult.bytes || file.size,
        format: cloudinaryResult.format || (isVideo ? 'mp4' : 'jpg'),
        mediaType: isVideo ? 'video' : 'image',
        duration: cloudinaryResult.duration || 0,
        width: cloudinaryResult.width || 0,
        height: cloudinaryResult.height || 0,
        owner: req.user.id,
        objects: detectedObjects.map((t) => t.toLowerCase()),
      });

      uploadedMedia.push(item);
    }

    res.status(201).json({
      message: `Successfully uploaded ${uploadedMedia.length} items`,
      media: uploadedMedia,
    });
  } catch (error) {
    console.error('Upload Error:', error);
    res.status(500).json({ message: 'Upload failed', error: error.message });
  }
};

// Get media items with optional search and favorite filters
export const getMedia = async (req, res) => {
  try {
    const { favorite, query, type } = req.query;
    const filter = { owner: req.user.id, isTrash: false };

    if (favorite === 'true') filter.isFavorite = true;
    if (type && type !== 'all') filter.mediaType = type;

    if (query && query.trim()) {
      const searchTerm = query.trim();
      filter.$or = [
        { title: { $regex: searchTerm, $options: 'i' } },
        { objects: { $regex: searchTerm, $options: 'i' } },
      ];
    }

    const media = await Media.find(filter).sort({ createdAt: -1 });
    res.status(200).json({ media });
  } catch (error) {
    res.status(500).json({ message: 'Failed to fetch media' });
  }
};

// Toggle favorite state
export const toggleFavorite = async (req, res) => {
  try {
    const item = await Media.findOne({ _id: req.params.id, owner: req.user.id });
    if (!item) return res.status(404).json({ message: 'Media not found' });

    item.isFavorite = !item.isFavorite;
    await item.save();

    res.status(200).json({ media: item });
  } catch (error) {
    res.status(500).json({ message: 'Failed to update favorite status' });
  }
};

// Move item to trash or restore from trash
export const toggleTrash = async (req, res) => {
  try {
    const { restore } = req.body;
    const item = await Media.findOne({ _id: req.params.id, owner: req.user.id });
    if (!item) return res.status(404).json({ message: 'Media not found' });

    item.isTrash = !restore;
    item.trashedAt = restore ? null : new Date();
    await item.save();

    res.status(200).json({
      message: restore ? 'Restored from trash' : 'Moved to trash',
      media: item,
    });
  } catch (error) {
    res.status(500).json({ message: 'Failed to update trash status' });
  }
};

// Retrieve all trashed items
export const getTrash = async (req, res) => {
  try {
    const media = await Media.find({ owner: req.user.id, isTrash: true }).sort({ trashedAt: -1 });
    res.status(200).json({ media });
  } catch (error) {
    res.status(500).json({ message: 'Failed to fetch trash' });
  }
};

// Permanently delete a single media item
export const deleteMediaPermanently = async (req, res) => {
  try {
    const item = await Media.findOne({ _id: req.params.id, owner: req.user.id, isTrash: true });
    if (!item) return res.status(404).json({ message: 'Media not found' });

    // Remove file asset from Cloudinary
    if (item.publicId) {
      await cloudinary.uploader.destroy(item.publicId, {
        resource_type: item.mediaType === 'video' ? 'video' : 'image',
      });
    }

    // Pull photo reference out of all albums
    await Album.updateMany({ photos: item._id }, { $pull: { photos: item._id } });

    // Remove media entry from database
    await item.deleteOne();

    res.status(200).json({ message: 'Media permanently deleted' });
  } catch (error) {
    res.status(500).json({ message: 'Failed to delete media' });
  }
};

// Empty all trashed media items permanently
export const emptyTrash = async (req, res) => {
  try {
    const trashedMedia = await Media.find({ owner: req.user.id, isTrash: true });

    for (const item of trashedMedia) {
      if (item.publicId) {
        await cloudinary.uploader.destroy(item.publicId, {
          resource_type: item.mediaType === 'video' ? 'video' : 'image',
        });
      }
      await Album.updateMany({ photos: item._id }, { $pull: { photos: item._id } });
      await item.deleteOne();
    }

    res.status(200).json({ message: `Emptied trash: ${trashedMedia.length} items removed` });
  } catch (error) {
    res.status(500).json({ message: 'Failed to empty trash' });
  }
};

// Calculate and return current storage metrics for user
export const getStorageStats = async (req, res) => {
  try {
    const userId = req.user.id;
    const activeMedia = await Media.find({ owner: userId, isTrash: false });

    const totalBytes = activeMedia.reduce((sum, p) => sum + (p.size || 0), 0);
    const videoCount = activeMedia.filter((p) => p.mediaType === 'video').length;
    const imageCount = activeMedia.length - videoCount;
    const favoriteCount = activeMedia.filter((p) => p.isFavorite).length;
    const albumCount = await Album.countDocuments({ owner: userId });

    res.status(200).json({
      mediaCount: activeMedia.length,
      imageCount,
      videoCount,
      favoriteCount,
      totalBytes,
      albumCount,
    });
  } catch (error) {
    res.status(500).json({ message: 'Failed to get storage stats' });
  }
};